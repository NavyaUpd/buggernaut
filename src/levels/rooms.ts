// BIJLI room data: all 11 single-screen rooms (CLAUDE.md §8). Authoritative level data; pure TS, no Phaser.
//
// Legend (40 × 22 tiles of 32 px; tile (x, y) is drawn at px (x*32, y*32 + 8)):
//   .  empty                     #  solid block              =  one-way platform (awning / balcony)
//   c  crayon cloud: one-way ONLY while lit (inside a finished comic panel, or BIJLI mode)
//   |  pole (climbable)          H  ladder (climbable)       X  splice point (climbable when it sits on a pole)
//   B  breaker                   M  master breaker (3-3)     L  lamp head (marker; real data in `lamps`)
//   P  spawn (exactly one)       E  exit                     D  Chinni's drawing (BIJLI power-up)
//   Z  storm-dragon drawing (optional: Chinni draws the storm asleep, strikes pause for a while)
//   n  Taar-Naag (live wire in the dark, bouncy snake in light)
//   ~  water (deadly while its circuit's breaker is closed)
//
// Coordinates in the metadata are [x, y] tiles. Lamp radius r is in tiles; its comic panel is
// x − 1.06r … x + 1.04r, y − 0.95r … room bottom (§9.3). Rails run between two pole-top cells.

export type Tile = readonly [x: number, y: number];

export interface LampDef {
  at: Tile;
  r: number;
  circuit: string;
  /** 'house' = the window of Chinni's house in 4-1; 'ward' = a window of the hospital in 3-2b. */
  kind?: 'lamp' | 'house' | 'ward';
  /** What the neighbours shout when this light comes back (speech bubble). */
  cheer?: string;
}

export interface RailDef {
  a: Tile;
  b: Tile;
  /** Omitted = a dead wire, grindable only in BIJLI mode. */
  circuit?: string;
}

export interface CircuitDef {
  id: string;
  splices: Tile[];
  /** Breaker (B or M) cell. Omitted = no breaker. */
  breaker?: Tile;
  /** Initial breaker state (default true = closed = live). */
  closed?: boolean;
  /** M: closing it after the splice triggers the skyline bloom and ends the chapter. */
  master?: boolean;
  /** The room's `~` water is live whenever this circuit's breaker is closed. */
  water?: boolean;
}

export interface StrikeDef {
  /** Left tile column and width in tiles. Phase offsets come from STRIKE.offsets in listed order. */
  x: number;
  w: number;
}

export interface HouseDef {
  x: number;
  y: number;
  w: number;
  h: number;
  /** 'hospital' = flat-roofed ward block with a red cross (3-2b). Default 'home'. */
  style?: 'home' | 'hospital';
}

export interface RoomDef {
  id: string;
  name: string;
  chapter: number;
  /** Chinni's caption on room entry (top-left, 3 s). */
  caption: string;
  /** Yellow caption box in the corner of this room's comic panels. */
  panelCaption: string;
  map: readonly string[];
  lamps: LampDef[];
  rails: RailDef[];
  circuits: CircuitDef[];
  strikes: StrikeDef[];
  /** Ambient lightning flashes (the comic peek). */
  lightning: boolean;
  /** Seconds until the first ambient flash (default LIGHTNING.firstAt). */
  firstFlash?: number;
  /** Rain intensity 0..1 (default 1). */
  rain?: number;
  /** Sleeping street dog, standing on this tile. */
  dog?: Tile;
  /** Chinni's house (4-1), background prop in tiles. */
  house?: HouseDef;
  /** One-line story beat / hint card shown on entry, after the caption (short, lowercase, Chinni or radio voice). */
  beat?: string;
  /** Seconds on the backup timer (hospital): run out and the room resets. */
  timer?: number;
  /** Exit is inactive until every circuit is powered. */
  gatedExit?: boolean;
  /** 3-3: powering everything triggers the skyline bloom and ends the chapter. */
  skyline?: boolean;
}

